# build-search-index.ps1 - regenerates site/search-index.js from the handbook pages.
# One-shot, committed so the index can be rebuilt without a build step or bundler. The index is a
# plain JS array of { p (page), id (anchor), t (heading), s (section text) } for both pages.
# Usage: pwsh -File tests/build-search-index.ps1
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
$siteDir = Join-Path $repoRoot 'site'
$pages = @('index.html', 'walkthrough.html')

function Get-Text([string]$p) { return [System.Text.Encoding]::UTF8.GetString([System.IO.File]::ReadAllBytes($p)) }
function Get-Plain([string]$s) {
    $s = $s -replace '(?s)<script[\s\S]*?</script>', ''
    $s = $s -replace '(?s)<style[\s\S]*?</style>', ''
    $s = $s -replace '(?s)<nav[\s\S]*?</nav>', ''
    $s = $s -replace '<[^>]+>', ' '
    $s = [System.Net.WebUtility]::HtmlDecode($s)
    return ($s -replace '\s+', ' ').Trim()
}

$entries = New-Object System.Collections.ArrayList
foreach ($page in $pages) {
    $html = Get-Text (Join-Path $siteDir $page)
    $headings = [regex]::Matches($html, '<h([1-4])[^>]*\bid="([^"]+)"[^>]*>(.*?)</h\1>')
    for ($i = 0; $i -lt $headings.Count; $i++) {
        $m = $headings[$i]
        $title = Get-Plain $m.Groups[3].Value
        $start = $m.Index + $m.Length
        $end = if ($i + 1 -lt $headings.Count) { $headings[$i + 1].Index } else { $html.Length }
        $section = Get-Plain $html.Substring($start, $end - $start)
        if ($section.Length -gt 320) { $section = $section.Substring(0, 320) + '...' }
        [void]$entries.Add([pscustomobject]@{ p = $page; id = $m.Groups[2].Value; t = $title; s = $section })
    }
}

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine('// Generated by tests/build-search-index.ps1 - do not edit by hand.')
[void]$sb.AppendLine('window.HARNESS_SEARCH_INDEX = [')
for ($i = 0; $i -lt $entries.Count; $i++) {
    $e = $entries[$i]
    $json = ($e | ConvertTo-Json -Compress)
    $comma = if ($i -lt $entries.Count - 1) { ',' } else { '' }
    [void]$sb.AppendLine('  ' + $json + $comma)
}
[void]$sb.AppendLine('];')
$out = Join-Path $siteDir 'search-index.js'
[System.IO.File]::WriteAllText($out, $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host ("search-index: {0} entries across {1}" -f $entries.Count, ($pages -join ', '))
